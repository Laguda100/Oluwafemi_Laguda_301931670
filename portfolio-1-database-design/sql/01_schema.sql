-- =====================================================================
-- Portfolio 1 - Crestfield University Student Result Portal
-- File   : 01_schema.sql
-- Engine : PostgreSQL 16
-- Purpose: Create the normalised (3NF/BCNF) relational schema with
--          keys, constraints and integrity triggers.
-- Re-runnable: drops and recreates everything.
-- =====================================================================

BEGIN;

DROP TABLE IF EXISTS result_audit, result, registration, course_offering,
                     academic_session, course, student, lecturer, programme,
                     department, faculty, grade_scale CASCADE;
DROP FUNCTION IF EXISTS fn_result_guard() CASCADE;
DROP FUNCTION IF EXISTS fn_result_audit() CASCADE;

-- ---------------------------------------------------------------------
-- Organisation structure: faculty -> department -> programme
-- ---------------------------------------------------------------------
CREATE TABLE faculty (
    faculty_id  SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(10)  NOT NULL UNIQUE,
    name        VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE department (
    department_id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    faculty_id    SMALLINT     NOT NULL REFERENCES faculty (faculty_id),
    code          VARCHAR(10)  NOT NULL UNIQUE,
    name          VARCHAR(100) NOT NULL,
    CONSTRAINT uq_department_name_per_faculty UNIQUE (faculty_id, name)
);

CREATE TABLE programme (
    programme_id   SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_id  SMALLINT     NOT NULL REFERENCES department (department_id),
    code           VARCHAR(12)  NOT NULL UNIQUE,
    name           VARCHAR(120) NOT NULL,
    degree_type    VARCHAR(10)  NOT NULL
                   CHECK (degree_type IN ('BSc', 'BEng', 'BA', 'MSc', 'MIT', 'PhD')),
    duration_years SMALLINT     NOT NULL CHECK (duration_years BETWEEN 1 AND 7)
);

-- ---------------------------------------------------------------------
-- People
-- ---------------------------------------------------------------------
CREATE TABLE lecturer (
    lecturer_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_id SMALLINT     NOT NULL REFERENCES department (department_id),
    staff_no      VARCHAR(12)  NOT NULL UNIQUE CHECK (staff_no ~ '^STF/[0-9]{4}$'),
    title         VARCHAR(10)  NOT NULL DEFAULT 'Dr.',
    first_name    VARCHAR(50)  NOT NULL,
    last_name     VARCHAR(50)  NOT NULL,
    email         VARCHAR(120) NOT NULL UNIQUE
                  CHECK (email ~* '^[A-Z0-9._%+-]+@[A-Z0-9.-]+\.[A-Z]{2,}$'),
    academic_rank VARCHAR(30)  NOT NULL
                  CHECK (academic_rank IN ('Graduate Assistant', 'Assistant Lecturer',
                                           'Lecturer II', 'Lecturer I', 'Senior Lecturer',
                                           'Associate Professor', 'Professor'))
);

CREATE TABLE student (
    student_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    matric_no     VARCHAR(20)  NOT NULL UNIQUE
                  CHECK (matric_no ~ '^CFU/[0-9]{4}/[0-9]{5}$'),
    programme_id  SMALLINT     NOT NULL REFERENCES programme (programme_id),
    first_name    VARCHAR(50)  NOT NULL,
    last_name     VARCHAR(50)  NOT NULL,
    other_names   VARCHAR(80),
    email         VARCHAR(120) NOT NULL UNIQUE
                  CHECK (email ~* '^[A-Z0-9._%+-]+@[A-Z0-9.-]+\.[A-Z]{2,}$'),
    date_of_birth DATE         NOT NULL CHECK (date_of_birth > DATE '1950-01-01'),
    gender        CHAR(1)      NOT NULL CHECK (gender IN ('M', 'F')),
    entry_year    SMALLINT     NOT NULL CHECK (entry_year BETWEEN 2000 AND 2100),
    current_level SMALLINT     NOT NULL DEFAULT 100
                  CHECK (current_level IN (100, 200, 300, 400, 500, 600, 700)),
    status        VARCHAR(12)  NOT NULL DEFAULT 'ACTIVE'
                  CHECK (status IN ('ACTIVE', 'SUSPENDED', 'GRADUATED', 'WITHDRAWN')),
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------
-- Curriculum and calendar
-- ---------------------------------------------------------------------
CREATE TABLE course (
    course_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_id SMALLINT     NOT NULL REFERENCES department (department_id),
    course_code   VARCHAR(8)   NOT NULL UNIQUE CHECK (course_code ~ '^[A-Z]{3} [0-9]{3}$'),
    title         VARCHAR(150) NOT NULL,
    credit_units  SMALLINT     NOT NULL CHECK (credit_units BETWEEN 1 AND 6),
    course_level  SMALLINT     NOT NULL CHECK (course_level IN (100, 200, 300, 400, 500)),
    semester      SMALLINT     NOT NULL CHECK (semester IN (1, 2))
);

CREATE TABLE academic_session (
    session_id  SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        CHAR(9)  NOT NULL UNIQUE CHECK (name ~ '^[0-9]{4}/[0-9]{4}$'),
    start_date  DATE     NOT NULL,
    end_date    DATE     NOT NULL,
    is_current  BOOLEAN  NOT NULL DEFAULT false,
    CONSTRAINT ck_session_dates CHECK (end_date > start_date)
);

-- Business rule: only ONE session can be the current session.
-- A partial unique index enforces this declaratively.
CREATE UNIQUE INDEX uq_one_current_session
    ON academic_session (is_current) WHERE is_current;

-- A course taught in a particular session by a particular lecturer.
CREATE TABLE course_offering (
    offering_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id     INTEGER     NOT NULL REFERENCES course (course_id),
    session_id    SMALLINT    NOT NULL REFERENCES academic_session (session_id),
    lecturer_id   INTEGER     NOT NULL REFERENCES lecturer (lecturer_id),
    capacity      SMALLINT    NOT NULL DEFAULT 200 CHECK (capacity > 0),
    result_status VARCHAR(10) NOT NULL DEFAULT 'OPEN'
                  CHECK (result_status IN ('OPEN', 'SUBMITTED', 'APPROVED')),
    CONSTRAINT uq_offering_course_session UNIQUE (course_id, session_id)
);

-- ---------------------------------------------------------------------
-- Registration and results
-- ---------------------------------------------------------------------
CREATE TABLE registration (
    registration_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id      INTEGER     NOT NULL REFERENCES student (student_id),
    offering_id     INTEGER     NOT NULL REFERENCES course_offering (offering_id),
    registered_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    status          VARCHAR(10) NOT NULL DEFAULT 'REGISTERED'
                    CHECK (status IN ('REGISTERED', 'DROPPED')),
    CONSTRAINT uq_registration_student_offering UNIQUE (student_id, offering_id)
);

-- One result per registration (1:0..1), so the PK is also the FK.
CREATE TABLE result (
    registration_id BIGINT       PRIMARY KEY REFERENCES registration (registration_id),
    ca_score        NUMERIC(4,1) NOT NULL CHECK (ca_score   BETWEEN 0 AND 30),
    exam_score      NUMERIC(4,1) NOT NULL CHECK (exam_score BETWEEN 0 AND 70),
    -- Derived, but maintained by the DBMS itself so it can never be inconsistent.
    total_score     NUMERIC(4,1) GENERATED ALWAYS AS (ca_score + exam_score) STORED,
    entered_by      INTEGER      NOT NULL REFERENCES lecturer (lecturer_id),
    entered_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ
);

-- Grading policy (5-point scale). A grade is looked up as the band with
-- the highest min_score <= total_score, so bands can never overlap or leave gaps.
CREATE TABLE grade_scale (
    grade       CHAR(1)      PRIMARY KEY,
    min_score   NUMERIC(4,1) NOT NULL UNIQUE CHECK (min_score BETWEEN 0 AND 100),
    grade_point SMALLINT     NOT NULL UNIQUE CHECK (grade_point BETWEEN 0 AND 5)
);

-- Every change to a score is recorded (no FK, so history survives deletes).
CREATE TABLE result_audit (
    audit_id        BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    registration_id BIGINT       NOT NULL,
    action          CHAR(1)      NOT NULL CHECK (action IN ('I', 'U', 'D')),
    old_ca_score    NUMERIC(4,1),
    old_exam_score  NUMERIC(4,1),
    new_ca_score    NUMERIC(4,1),
    new_exam_score  NUMERIC(4,1),
    changed_by      TEXT         NOT NULL DEFAULT current_user,
    changed_at      TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------
-- Trigger 1: results of an APPROVED course offering are locked.
-- ---------------------------------------------------------------------
CREATE FUNCTION fn_result_guard() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    v_reg    BIGINT;
    v_status TEXT;
BEGIN
    IF TG_OP = 'DELETE' THEN
        v_reg := OLD.registration_id;
    ELSE
        v_reg := NEW.registration_id;
    END IF;

    SELECT o.result_status INTO v_status
    FROM registration r
    JOIN course_offering o ON o.offering_id = r.offering_id
    WHERE r.registration_id = v_reg;

    IF v_status = 'APPROVED' THEN
        RAISE EXCEPTION 'Result for registration % is locked: course result already APPROVED', v_reg;
    END IF;

    IF TG_OP = 'UPDATE' THEN
        NEW.updated_at := now();
    END IF;

    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_result_guard
    BEFORE INSERT OR UPDATE OR DELETE ON result
    FOR EACH ROW EXECUTE FUNCTION fn_result_guard();

-- ---------------------------------------------------------------------
-- Trigger 2: audit trail of every score change.
-- ---------------------------------------------------------------------
CREATE FUNCTION fn_result_audit() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        INSERT INTO result_audit (registration_id, action, new_ca_score, new_exam_score)
        VALUES (NEW.registration_id, 'I', NEW.ca_score, NEW.exam_score);
    ELSIF TG_OP = 'UPDATE' THEN
        INSERT INTO result_audit (registration_id, action, old_ca_score, old_exam_score,
                                  new_ca_score, new_exam_score)
        VALUES (NEW.registration_id, 'U', OLD.ca_score, OLD.exam_score,
                NEW.ca_score, NEW.exam_score);
    ELSE
        INSERT INTO result_audit (registration_id, action, old_ca_score, old_exam_score)
        VALUES (OLD.registration_id, 'D', OLD.ca_score, OLD.exam_score);
    END IF;
    RETURN NULL;   -- return value of an AFTER trigger is ignored
END;
$$;

CREATE TRIGGER trg_result_audit
    AFTER INSERT OR UPDATE OR DELETE ON result
    FOR EACH ROW EXECUTE FUNCTION fn_result_audit();

COMMIT;

-- Note: apart from PK/UNIQUE indexes, no secondary indexes are created here
-- on purpose. Portfolio 2 measures query plans before and after indexing.
